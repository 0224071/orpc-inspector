export const messages = { 'en': en, 'zh-TW': zhTW }

export type Locale = keyof typeof messages

/** Active panel language; set from the panel settings */
export const locale = ref<Locale>('en')

/** Look up a message in the active language and fill `{name}` placeholders */
export function t(key: MessageKey, params?: Record<string, string | number>) {
  const text = messages[locale.value][key]
  return params
    ? text.replace(/\{(\w+)\}/g, (match, name: string) => (name in params
        ? String(params[name])
        : match))
    : text
}

/** Counted messages: base names that have both a `…One` and a `…Many` key */
export type CountKey = {
  [K in MessageKey]: K extends `${infer Base}One`
    ? `${Base}Many` extends MessageKey
      ? Base
      : never
    : never
}[MessageKey]

/** Look up the singular or plural form of a counted message and fill `{count}` */
export function tc(key: CountKey, count: number, params?: Record<string, string | number>) {
  const form = count === 1
    ? 'One'
    : 'Many'
  return t(`${key}${form}`, { ...params, count })
}
